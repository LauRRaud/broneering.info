async function prepared(kind:string,csv:string){
  const batch=await uploadImport(owner,{...input(),kind},csv);
  const headers=csv.split('\n')[0].split(',');
  await previewImport(owner,{tenantId,id:batch.id,version:1,mapping:Object.fromEntries(headers.map((h,i)=>[h,i])),timezone:'Europe/Tallinn',cutoverAt:'2030-01-01T00:00:00Z'});
  return {tenantId,id:batch.id,version:2,skipInvalid:false,skipDuplicates:false};
}
it('commits all four kinds, retries once and never sends an initial mail wave',async()=>{
  const customers=await prepared('customers','name,email\nFirst Person,same@example.invalid\nSecond Person,same@example.invalid');
  const results=await Promise.all([commitImport(owner,customers),commitImport(owner,customers)]);
  expect(results[0]).toEqual(results[1]);expect(results[0].imported).toBe(2);
  expect((await db.query('SELECT count(*)::int n FROM customers WHERE tenant_id=$1',[tenantId])).rows[0].n).toBe(2);
  const group=(await db.query("INSERT INTO service_groups(tenant_id,name) VALUES($1,'Imported') RETURNING id",[tenantId])).rows[0].id;
  await commitImport(owner,await prepared('services',`name,groupId,priceCents,duration\nImported service,${group},3500,60`));
  await commitImport(owner,await prepared('staff','name\nImported staff'));
  const service=(await db.query('SELECT id,online FROM services WHERE tenant_id=$1',[tenantId])).rows[0];
  const staff=(await db.query('SELECT id,online FROM staff WHERE tenant_id=$1',[tenantId])).rows[0];
  expect(service.online).toBe(false);expect(staff.online).toBe(false);
  await db.query('INSERT INTO staff_services(tenant_id,service_id,staff_id) VALUES($1,$2,$3)',[tenantId,service.id,staff.id]);
  const bookingCsv=`serviceId,staffId,name,email,startAt,priceCents,duration\n${service.id},${staff.id},First Person,same@example.invalid,2030-01-15T10:00:00+02:00,3500,60`;
  const booking=await prepared('bookings',bookingCsv);
  const conflicting=await prepared('bookings',bookingCsv.replace('First Person','Different Person'));
  expect((await commitImport(owner,booking)).imported).toBe(1);
  expect((await db.query('SELECT source,customer_notifications,is_test FROM bookings WHERE tenant_id=$1',[tenantId])).rows[0]).toEqual({source:'import',customer_notifications:false,is_test:false});
  expect((await db.query('SELECT count(*)::int n FROM outbox WHERE tenant_id=$1',[tenantId])).rows[0].n).toBe(0);
  await expect(commitImport(owner,conflicting)).rejects.toMatchObject({code:'IMPORT_OVERLAP'});
  expect((await importState(owner,tenantId,conflicting.id)).batches[0].status).toBe('preview');
  await previewImport(owner,{tenantId,id:conflicting.id,version:2,mapping:Object.fromEntries(bookingCsv.split('\n')[0].split(',').map((h,i)=>[h,i])),timezone:'Europe/Tallinn',cutoverAt:'2030-01-01T00:00:00Z'});
  expect((await importState(owner,tenantId,conflicting.id)).rows[0].error_code).toBe('BOOKING_OVERLAP');
  const enable={tenantId,id:booking.id,version:3,action:'enable-reminders'};
  await expect(importLifecycle(owner,enable)).rejects.toMatchObject({code:'REMINDER_POLICY_REQUIRED'});
  await db.query('UPDATE tenants SET reminder_minutes=1440,management_link_hours=24 WHERE id=$1',[tenantId]);
  expect(await importLifecycle(owner,enable)).toMatchObject({scheduled:1});
  expect(await importLifecycle(owner,enable)).toMatchObject({scheduled:0});
  const notices=(await db.query('SELECT kind,status,next_attempt_at FROM outbox WHERE tenant_id=$1',[tenantId])).rows;
  expect(notices).toHaveLength(1);expect(notices[0]).toMatchObject({kind:'booking.reminder',status:'pending'});
  expect(notices[0].next_attempt_at.getTime()).toBeGreaterThan(Date.now());
  expect((await db.query('SELECT customer_notifications FROM bookings WHERE tenant_id=$1',[tenantId])).rows[0].customer_notifications).toBe(true);
});
