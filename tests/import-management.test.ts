it('normalizes mapped rows, flags duplicates and validates preview versions',async()=>{
  const batch=await uploadImport(owner,input(),'Client,Email\n  First Person ,same@example.invalid\nSecond Person,same@example.invalid\nSecond Person,same@example.invalid\nX,bad-email');
  const d={tenantId,id:batch.id,version:1,mapping:{name:0,email:1},timezone:'Europe/Tallinn',cutoverAt:'2030-01-01T00:00:00Z'};
  expect(await previewImport(owner,d)).toMatchObject({version:2,errors:1,warnings:1});
  const state=await importState(owner,tenantId,batch.id);
  expect(state.rows[0].normalized).toMatchObject({name:'First Person',email:'same@example.invalid'});
  expect(state.rows[1].warning_codes).toEqual([]);
  expect(state.rows[2].warning_codes).toEqual(['DUPLICATE_ROW']);
  expect(state.rows[3].error_code).toContain('FIELD_email');
  await expect(previewImport(owner,d)).rejects.toMatchObject({code:'VERSION_CONFLICT'});
  await expect(previewImport(owner,{...d,version:2,mapping:{name:0,email:0}})).rejects.toMatchObject({code:'IMPORT_MAPPING'});
});
